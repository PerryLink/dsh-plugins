#!/usr/bin/env node
/**
 * Regenerate the Evidence columns of ../RELEASE-MANIFEST.md from the repos
 * themselves — never by hand.
 *
 *   Acceptance rows = data rows in ../<dir>/ACCEPTANCE.csv (header excluded)
 *   Tests           = total reported by `node --test test/*.test.mjs`
 *
 * The package/suite version, release tag and state columns are also projected
 * from dsh-plugins/packages.json so this table cannot drift from it.
 *
 * Usage:
 *   node scripts/release-evidence.mjs --write            # build + test + write
 *   node scripts/release-evidence.mjs --write --no-build # reuse existing lib/
 *   node scripts/release-evidence.mjs                    # print only
 */
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const projectRoot = path.resolve(root, '..');
const manifestPath = path.join(projectRoot, 'RELEASE-MANIFEST.md');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'packages.json'), 'utf8'));
const write = process.argv.includes('--write');
const build = !process.argv.includes('--no-build');

const run = (cmd, args, cwd) => {
  const r = spawnSync(cmd, args, {
    cwd,
    encoding: 'utf8',
    shell: process.platform === 'win32',
    timeout: 15 * 60 * 1000,
  });
  if (r.error) throw r.error;
  return { status: r.status, output: `${r.stdout || ''}${r.stderr || ''}` };
};

function acceptanceRows(dir) {
  const csvPath = path.join(dir, 'ACCEPTANCE.csv');
  if (!fs.existsSync(csvPath)) return null;
  const lines = fs.readFileSync(csvPath, 'utf8').split(/\r?\n/).filter((line) => line.trim() !== '');
  if (!lines.length || !/^req_id\s*,/.test(lines[0])) {
    throw new Error(`${csvPath}: expected a req_id header row`);
  }
  return lines.length - 1;
}

function testsTotal(dir) {
  const testDir = path.join(dir, 'test');
  if (!fs.existsSync(testDir)) return null;
  const files = fs.readdirSync(testDir).filter((f) => f.endsWith('.test.mjs')).sort();
  if (!files.length) return null;
  if (build) {
    const built = run('pnpm', ['build'], dir);
    if (built.status !== 0) throw new Error(`${path.basename(dir)}: pnpm build failed\n${built.output.slice(-2000)}`);
  }
  const tested = run(process.execPath, ['--test', ...files.map((f) => path.join('test', f))], dir);
  const match = tested.output.match(/^ℹ tests (\d+)$/m) || tested.output.match(/^# tests (\d+)$/m);
  if (!match) throw new Error(`${path.basename(dir)}: no "tests N" line in node --test output`);
  const fail = Number((tested.output.match(/^ℹ fail (\d+)$/m) || tested.output.match(/^# fail (\d+)$/m) || [0, 0])[1]);
  if (tested.status !== 0 || fail > 0) {
    throw new Error(`${path.basename(dir)}: ${fail} test(s) failed\n${tested.output.slice(-3000)}`);
  }
  return { tests: Number(match[1]), fail };
}

const entries = [...manifest.packages, ...manifest.suites];
const evidence = new Map();
for (const p of manifest.packages) {
  const dir = path.join(projectRoot, p.dir);
  const rows = acceptanceRows(dir);
  const result = testsTotal(dir);
  if (rows === null) throw new Error(`${p.name}: no ACCEPTANCE.csv in ${p.dir}`);
  if (result === null) throw new Error(`${p.name}: no test/*.test.mjs in ${p.dir}`);
  evidence.set(p.name, { rows, tests: result.tests });
  console.log(`${p.name.padEnd(22)} rows=${String(rows).padStart(3)} tests=${String(result.tests).padStart(3)}`);
}
for (const s of manifest.suites) evidence.set(s.name, { rows: null, tests: null });

const cell = (v) => (v === null ? '—' : String(v));
const table = [
  '| Package | Version | GitHub release | State | Acceptance rows | Tests |',
  '|---|---|---|---|---|---|',
  ...entries.map((p) => {
    const e = evidence.get(p.name);
    return `| \`${p.name}\` | \`${p.version}\` | \`v${p.version}\` | ${p.status || 'active'} | ${cell(e.rows)} | ${cell(e.tests)} |`;
  }),
  '',
  '> Generated by `node scripts/release-evidence.mjs --write`; do not hand-edit these columns. **Acceptance rows** = data rows in `../<dir>/ACCEPTANCE.csv` (header excluded). **Tests** = total reported by `node --test test/*.test.mjs` (includes skipped). `dsh-einvoice`\'s A02 row is `out_of_scope` and is counted like every other data row. The two suites are installers: they have no `ACCEPTANCE.csv` and no test suite, so their evidence stays the install smoke recorded in `CI-STATUS.md`.',
  '',
].join('\n');

const start = manifestTextIndex();
function manifestTextIndex() {
  const text = fs.readFileSync(manifestPath, 'utf8');
  const headerMatch = /^\| Package \| Version \| GitHub release \| State \|.*$/m.exec(text);
  if (!headerMatch) throw new Error('RELEASE-MANIFEST.md: evidence table header not found');
  const header = headerMatch.index;
  const totals = text.indexOf('\n**Totals:**', header);
  if (totals < 0) throw new Error('RELEASE-MANIFEST.md: **Totals:** line not found after the table');
  return { text, header, end: totals };
}

if (write) {
  const next = `${start.text.slice(0, start.header)}${table}${start.text.slice(start.end)}`;
  fs.writeFileSync(manifestPath, next);
  console.log(`wrote ${path.relative(root, manifestPath)} (${entries.length} rows)`);
} else {
  console.log(table);
  console.log('(dry run; pass --write to update RELEASE-MANIFEST.md)');
}
